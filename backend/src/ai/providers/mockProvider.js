// DEMO ONLY. Produces a clearly labelled placeholder evaluation so the whole workflow can be
// demonstrated with no API key and no cost. It does NOT assess legal quality.
async function complete({ meta }) {
  const words = meta.submissionText.split(/\s+/).filter(Boolean);
  const factor = Math.min(words.length / 250, 1);
  const quote = words.slice(0, 12).join(' ');
  return {
    text: JSON.stringify({
      criteria: meta.criteria.map((c) => ({
        criterionId: c.id,
        score: Math.round(c.maxScore * (0.5 + 0.3 * factor)),
        rationale: `DEMO MOCK: placeholder reasoning for "${c.name}". No real AI model was used.`,
        evidenceQuotes: [quote],
        observations: [`The submission has ${words.length} words.`],
        inferences: ['DEMO MOCK: no real inference was made.'],
        confidence: 0.6,
        canAssess: true,
      })),
      strengths: ['DEMO MOCK: the submission is structured as a notice.'],
      weaknesses: ['DEMO MOCK: a real model would identify weaknesses here.'],
      feedbackSuggestions: ['DEMO MOCK: replace this with your own feedback.'],
      authoritiesMentioned: [],
      flags: [{ type: 'DEMO_MOCK', message: 'Generated by the built-in DEMO mock, not a real AI model.' }],
    }),
    usage: null,
    model: 'demo-mock-1',
  };
}

module.exports = { name: 'mock', complete };